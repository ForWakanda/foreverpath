local root = assert(arg[1], "usage: lua5.1 tools/import-dungeon-catalog.lua <source checkout>")
local data = {}
local env = { pairs=pairs, ipairs=ipairs, type=type, tostring=tostring, tonumber=tonumber,
    string=string, table=table, math=math, assert=assert }
for _, file in ipairs({"QuestData", "QuestDataLevel35", "DungeonData", "QuestDataBeta30",
    "QuestDataDalaran", "QuestDataClassic", "QuestFollowUps", "PrerequisiteReview", "QuestMetadata"}) do
    local f = assert(io.open(root .. "/DungeonQuestTrackerForever/Data/" .. file .. ".lua"))
    local text = f:read("*a"):gsub("^\239\187\191", ""); f:close()
    local chunk = assert(loadstring(text, file)); setfenv(chunk, env); chunk("catalog", data)
end
local function pick(t, keys)
    local out = {}
    for key in keys:gmatch("%S+") do out[key] = t[key] end
    return out
end
local out = {dungeons={}, quests={}}
for key, d in pairs(data.dungeons) do
    out.dungeons[key] = pick(d, "name minLevel recommendedLevel location quests")
end
for id, q in pairs(data.quests) do
    out.quests[id] = pick(q, "name faction classes races minLevel questLevel pickup pickupType prerequisites followUpOf breadcrumbOnly classicSourceOnly newInForever")
    out.quests[id].conflict = q.verification and q.verification.conflict
end
local function serialize(v)
    if type(v) == "string" then return string.format("%q", v):gsub("\\\n", "\\n") end
    if type(v) ~= "table" then return tostring(v) end
    local keys, parts = {}, {}
    for k in pairs(v) do keys[#keys+1] = k end
    table.sort(keys, function(a,b) if type(a)==type(b) then return a<b end return type(a)<type(b) end)
    for _, k in ipairs(keys) do parts[#parts+1] = "[" .. serialize(k) .. "]=" .. serialize(v[k]) end
    return "{" .. table.concat(parts, ",") .. "}"
end
print("-- Generated by tools/import-dungeon-catalog.lua; do not edit by hand.")
print("-- DungeonQuestTracker b4ae5a478d0f96c842c13d5ad96bb4adb11f15df, MIT (THIRD_PARTY_NOTICES.txt).")
print("-- Community / Classic reference, NOT proof of current Forever eligibility or complete coverage.")
print("local _, FP = ...\nFP.DungeonCatalog = { dungeons = {}, quests = {} }")
for _, section in ipairs({"dungeons", "quests"}) do
    local keys = {}; for k in pairs(out[section]) do keys[#keys+1]=k end; table.sort(keys)
    for _, k in ipairs(keys) do print("FP.DungeonCatalog." .. section .. "[" .. serialize(k) .. "] = " .. serialize(out[section][k])) end
end
